import os
from pathlib import Path


def _env_path(name, default):
    """A path override from the environment, relative to the project root. Used by
    `run_pipeline.py --smoke` to write a throw-away run into outputs_smoke/ instead of
    over the reportable outputs/."""
    v = os.environ.get(name)
    if not v:
        return default
    p = Path(v)
    return p if p.is_absolute() else PROJECT_ROOT / p


def _env_int(name, default):
    """Env overrides exist so the pipeline can be smoke-tested in seconds
    without editing this file. Never set them for a run whose numbers will be
    reported - the reported run must use the defaults below."""
    return int(os.environ.get(name, default))

