"""
Central configuration.

Everything that is a *choice* lives here rather than being scattered through the
code, so that Appendix A of the report can be generated by simply printing this
module. If a number here is a guess rather than a measurement, it is marked
CONFIRM and must be resolved before that number appears in the report.
"""
import os
from pathlib import Path


def _env_int(name, default):
    """Env overrides exist so the pipeline can be smoke-tested in seconds
    without editing this file. Never set them for a run whose numbers will be
    reported - the reported run must use the defaults below."""
    return int(os.environ.get(name, default))

# --------------------------------------------------------------------------
# Paths
# --------------------------------------------------------------------------
PROJECT_ROOT = Path(__file__).resolve().parents[1]
DATA_DIR     = PROJECT_ROOT / "dataset" / "PowerSystem"
OUTPUT_DIR   = PROJECT_ROOT / "outputs"
CACHE_DIR    = OUTPUT_DIR / "cache"

# The three released variants are the SAME 15 captures in the SAME row order,
# differing only in the `marker` column. That is what lets us read the label
# from one variant and the scenario id from another and join them positionally.
VARIANT_MULTICLASS = DATA_DIR / "multiclass"   # marker = scenario id (37 classes)
VARIANT_TRIPLE     = DATA_DIR / "triple"       # marker = Attack | Natural | NoEvents
VARIANT_BINARY     = DATA_DIR / "binary"       # marker = Attack | Natural

FILE_IDS = list(range(1, 16))                  # data1.csv .. data15.csv

# --------------------------------------------------------------------------
# Label choice
# --------------------------------------------------------------------------
# y for E1-E7 is the 3-class label. The architectural claim is about CLASS
# FAMILIES (is this an attack, a natural fault, or nothing), not about telling
# scenario 23 from scenario 24. The 37-way scenario id is used as the leakage
# grouping key and as the held-out unit in E8, not as a training target.
TARGET = "y_triple"
CLASS_ORDER = ["NoEvents", "Natural", "Attack"]   # fixed order => stable report columns
ATTACK_CLASS = "Attack"                            # positive class for E6

# --------------------------------------------------------------------------
# Inf policy (see README "KNOWN LANDMINE")
# --------------------------------------------------------------------------
# All 10,906 Inf cells sit in exactly four columns: R{1..4}-PA:Z, the apparent
# impedance Z = V / I. Z -> Inf is not corruption; it is physics, and it means
# "no current through this line" (open breaker / de-energised line). So:
#   1. the Inf itself becomes NaN and the tree model learns a default direction
#      for it (XGBoost and HistGradientBoosting both do this natively), and
#   2. we optionally keep a companion boolean column recording WHERE the Inf
#      was, because "this line went open" is a real, cheap, physical signal we
#      would be throwing away otherwise.
INF_POLICY = "nan"          # "nan" | "clip" | "drop_rows"
ADD_INF_INDICATORS = True   # adds R{n}-PA:Z__was_inf (4 extra columns)

# --------------------------------------------------------------------------
# Splitting
# --------------------------------------------------------------------------
# VERIFIED by inspection of all 15 files: within a file, every scenario occupies
# ONE contiguous block of rows, and a scenario never reappears in a second block
# of the same file. So an "event instance" == (file_id, scenario_id), and row
# order inside a block is time order. 15 files x 37 scenarios = 553 event
# instances (data9 and data10 carry 36 scenarios each, not 37).
GROUP_KEY        = "event_id"     # leakage-safe unit for E1-E7
SCENARIO_KEY     = "scenario_id"  # held-out unit for E8
N_SPLITS         = _env_int("PP_N_SPLITS", 5)   # StratifiedGroupKFold folds
RANDOM_SEED      = 42

# --------------------------------------------------------------------------
# Deployment constants used to turn model numbers into architecture numbers
# --------------------------------------------------------------------------
# CONFIRM: the MSU/ORNL testbed PMUs are documented at 120 samples/second.
# Every bandwidth and false-alerts-per-24h figure scales linearly with this, so
# it must be sourced from the upstream README PDF before it enters the report.
SAMPLE_RATE_HZ      = 120
BYTES_PER_FEATURE   = 4      # float32 on the wire
# E6 converts a false-positive RATE into false alerts per 24h. That needs an
# assumed benign duty cycle: what fraction of real operating time is quiet.
# The dataset is ~71% attack rows, which is nothing like a real substation.
# CONFIRM this assumption or present E6 as a curve over it.
BENIGN_FRACTION_REAL = 0.999

# --------------------------------------------------------------------------
# Shared model budget
# --------------------------------------------------------------------------
# E1 is only a fair comparison if every modality view gets the IDENTICAL model
# and the IDENTICAL hyperparameter budget. These are deliberately modest and
# deliberately frozen; do not tune per view.
MODEL_PARAMS = dict(
    n_estimators=_env_int("PP_N_ESTIMATORS", 300),
    max_depth=6,
    learning_rate=0.1,
    subsample=0.9,
    colsample_bytree=0.9,
    reg_lambda=1.0,
)

# E3 sweep: feature-budget ladder
FEATURE_BUDGETS = [1, 2, 3, 5, 8, 12, 16, 20, 24, 32, 48, 64, 96, 128]
# k* = smallest budget whose macro-F1 is within this tolerance of the full model
KSTAR_TOLERANCE = 0.01

# E2: a verdict counts as "confident and correct" only if the model predicts the
# right class with at least this probability for this many consecutive samples.
# The sustain requirement stops a single lucky frame being reported as detection.
E2_CONFIDENCE   = 0.80
E2_SUSTAIN_ROWS = 3

for _d in (OUTPUT_DIR, CACHE_DIR):
    _d.mkdir(parents=True, exist_ok=True)
